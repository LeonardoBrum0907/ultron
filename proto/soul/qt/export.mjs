// Writes the Qt avatar's generated header (src/soul_generated.h) from the soul's own
// JavaScript: the shader, the palettes, the states, the particle budgets and timings. The
// JavaScript stays the one source, so the native avatar moves and colours the same way.
//   npm run export:qt          (export.test.js fails while the header is out of date)

import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { AVATAR_FRAME, AVATAR_QUALITY } from '../avatar.js'
import { AVATAR_STATES } from '../avatar-states.js'
import { SOUL_PALETTE_NAMES, SOUL_PALETTES } from '../palettes.js'
import { SOUL_FRAGMENT, SOUL_VERTEX } from '../shaders.js'
import { ASSEMBLY_END, CURRENTS, FLIGHT, PART } from '../swarm.js'
import { TINT } from '../tint.js'
import { TRAIL_N } from '../touch.js'

/** Where the header goes. */
export const HEADER_PATH = fileURLToPath(new URL('./src/soul_generated.h', import.meta.url))

const CHUNK = 6000 // chars per raw string piece: MSVC refuses longer literals (C2026)
const FLYING_PARTS = Object.keys(PART).filter((part) => FLIGHT[part]) // core .. ember, in PART order

/**
 * The header's text.
 * @returns {string}
 * @example writeFileSync(HEADER_PATH, soulHeader())
 */
export function soulHeader() {
  return [
    '// Generated by proto/soul/qt/export.mjs from the soul\'s JavaScript (shaders.js, palettes.js,',
    '// avatar-states.js, avatar.js, swarm.js, tint.js, touch.js). Do not edit: npm run export:qt.',
    '#pragma once',
    '',
    'namespace soul::generated {',
    '',
    ...constants(),
    '',
    ...palettes(),
    '',
    ...states(),
    '',
    ...budgets(),
    '',
    `inline constexpr const char *kVertexShader =\n${rawPieces(desktopGlsl(SOUL_VERTEX, 'vertex'))};`,
    '',
    `inline constexpr const char *kFragmentShader =\n${rawPieces(desktopGlsl(SOUL_FRAGMENT, 'fragment'))};`,
    '',
    '} // namespace soul::generated',
    '',
  ].join('\n')
}

/**
 * The WebGL 1 shader as desktop GLSL 3.30 core (what QOpenGLWidget gets on Windows, Linux
 * and macOS), its comments and blank lines dropped to keep the string short.
 * @param {string} source GLSL ES 1.00 as three.js gets it (no precision line: three adds one)
 * @param {'vertex' | 'fragment'} stage
 * @returns {string}
 */
export function desktopGlsl(source, stage) {
  const body = source
    .split('\n')
    .map((line) => line.replace(/\/\/.*$/, '').trimEnd())
    .filter((line) => line.trim())
    .join('\n')
    .replace(/\battribute\b/g, 'in')
    .replace(/\bvarying\b/g, stage === 'vertex' ? 'out' : 'in')
    .replace(/\bgl_FragColor\b/g, 'soulFragColor')
  const head = stage === 'vertex' ? '#version 330 core' : '#version 330 core\nout vec4 soulFragColor;'
  return `${head}\n${body}\n`
}

const f = (x) => (Number.isInteger(x) ? `${x}.0f` : `${x}f`)
const vec3 = (rgb) => `{${rgb.map(f).join(', ')}}`

function constants() {
  return [
    `inline constexpr int kCurrents = ${CURRENTS};`,
    `inline constexpr int kTrailN = ${TRAIL_N};`,
    `inline constexpr float kAssemblyEnd = ${f(ASSEMBLY_END)};`,
    `inline constexpr float kFrameBottom = ${f(AVATAR_FRAME.bottom)}, kFrameTop = ${f(AVATAR_FRAME.top)}, kFrameMinWidth = ${f(AVATAR_FRAME.minWidth)};`,
    `inline constexpr float kTintSettle = ${f(TINT.settle)}, kTintHurry = ${f(TINT.hurry)};`,
    `inline constexpr int kPaletteCount = ${SOUL_PALETTE_NAMES.length};`,
  ]
}

function palettes() {
  const rows = Object.entries(SOUL_PALETTES).map(([name, p]) => `    {"${name}", ${vec3(p.hot)}, ${vec3(p.mid)}, ${vec3(p.cool)}},`)
  return ['struct PaletteDef { const char *name; float hot[3], mid[3], cool[3]; };', 'inline constexpr PaletteDef kPalettes[] = {', ...rows, '};']
}

function states() {
  const rows = Object.entries(AVATAR_STATES).map(([name, s]) => `    {"${name}", "${s.palette}", ${f(s.energy)}, ${f(s.pace)}},`)
  return ['struct StateDef { const char *name; const char *palette; float energy, pace; };', 'inline constexpr StateDef kStates[] = {', ...rows, '};']
}

// Per flying part (core, halo, flame, smoke, ember): when it sets off and how long it flies,
// and how many particles each quality gives it.
function budgets() {
  const flight = FLYING_PARTS.map((part) => {
    const { at, spread, dur } = FLIGHT[part]
    return `    {${f(at)}, ${f(spread)}, ${f(dur[0])}, ${f(dur[1])}}, // ${part}`
  })
  const counts = (q) => `{${FLYING_PARTS.map((part) => AVATAR_QUALITY[q].parts[part]).join(', ')}}`
  return [
    'struct FlightDef { float at, spread, durMin, durMax; };',
    `inline constexpr FlightDef kFlight[${FLYING_PARTS.length}] = {`,
    ...flight,
    '};',
    `inline constexpr int kBudgetFull[${FLYING_PARTS.length}] = ${counts('full')};`,
    `inline constexpr int kBudgetLite[${FLYING_PARTS.length}] = ${counts('lite')};`,
    `inline constexpr float kDensityFull = ${f(AVATAR_QUALITY.full.density)}, kDensityLite = ${f(AVATAR_QUALITY.lite.density)};`,
  ]
}

// Adjacent raw string literals, each short enough for every compiler, split between lines.
function rawPieces(text) {
  const pieces = ['']
  for (const line of text.split(/(?<=\n)/)) {
    if (pieces.at(-1).length + line.length > CHUNK) pieces.push('')
    pieces[pieces.length - 1] += line
  }
  return pieces.map((piece) => `    R"GLSL(${piece})GLSL"`).join('\n')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(HEADER_PATH, soulHeader())
  console.log(`wrote ${HEADER_PATH}`)
}
